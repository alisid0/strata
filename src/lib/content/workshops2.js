/** All extra-series modules (II + III + IV) for a track, in WorkshopLab's shape. */
export function getSeriesIIModules(track) {
  const entries = [
    ...(SERIES_II[track] || []),
    ...(SERIES_III[track] || []),
    ...(SERIES_IV[track] || [])
  ];
  return entries.map(({ items, ...meta }) => ({
    ...meta,
    getWorkshop: () => clone(items)
  }));
}
